package scripts::DBUpdateTo11_1::SwitchStatisticsReportFormat;

use v5.26;
use strict;
use warnings;
use namespace::autoclean;
use utf8;

use parent qw(scripts::DBUpdateTo11_1::Base);

# core module

# CPAN modules

# OTOBO modules

our @ObjectDependencies = (
    'Kernel::Config',
    'Kernel::System::Log',
    'Kernel::System::SysConfig',
    'Kernel::System::Console::Command::Maint::Stats::Reports::SwitchFormat',
);

=for stopwords gnuplot

=head1 NAME

scripts::DBUpdateTo11_1::SwitchStatisticsReportFormat - Gnuplot is the preferred chart generation backend

=head1 DESCRIPTION

Up the OTOBO 11.0.x the charts in the statistics report were generated by taking screenshots
from the Chromium browser. This means that an installation of Chromium was required.
In 11.1.x the preferred way of generating charts is to call the program I<gnuplot>. This migration
modules migrates from the Chromium solution to the Gnuplot solution. For that purpose
the console command C<Stats/Reports/SwitchFormat> is used.

Migrating the chart format is not problematic in Docker based installations. In native installations there is
no guarantee that I<gnuplot> is available. Therefore the migration is only done when I<gnuplot> is detected.

=cut

sub Run {
    my ( $Self, %Param ) = @_;

    my $SysConfigObject = $Kernel::OM->Get('Kernel::System::SysConfig');
    my $ConfigObject    = $Kernel::OM->Get('Kernel::Config');
    my $LogObject       = $Kernel::OM->Get('Kernel::System::Log');

    # check availablilty of gnuplot
    my $Key        = 'Gnuplot::Bin';
    my $GnuplotBin = $ConfigObject->Get($Key);

    # If Gnuplot::Bin is not yet configured then activate it when available
    if ( !$GnuplotBin ) {
        eval {
            my %Setting = $SysConfigObject->SettingGet(
                Name => $Key,
            );

            # nothing to do when Gnuplot::Bin is already active
            return if $Setting{IsValid};

            # no searching in the PATH
            my $Bin = $Setting{EffectiveValue};

            # Do not activate when there is no executable gnuplot binary.
            # There is no check whether $Bin is a file, as it often is a symlink to /etc/alternatives/gnuplot
            return unless -x $Bin;

            my $ExclusiveLockGUID = $SysConfigObject->SettingLock(
                UserID    => 1,
                Force     => 1,
                DefaultID => $Setting{DefaultID},
            );

            return unless $ExclusiveLockGUID;

            my %SettingUpdateResult = $SysConfigObject->SettingUpdate(
                Name              => $Key,
                IsValid           => 1,
                UserID            => 1,
                ExclusiveLockGUID => $ExclusiveLockGUID,
                EffectiveValue    => $Bin,
            );

            if ( !$SettingUpdateResult{Success} ) {
                $LogObject->Log(
                    Priority => 'error',
                    Message  => 'Could not activate Gnuplot::Bin.',
                );

                return;
            }

            $SysConfigObject->SettingUnlock(
                UserID    => 1,
                DefaultID => $Setting{DefaultID},
            );

            my %DeploymentResult = $SysConfigObject->ConfigurationDeploy(
                Comments      => "UpgradeTo11.1 - Activate Gnuplot::Bin.",
                UserID        => 1,
                Force         => 1,
                DirtySettings => [$Key],
                NoValidation  => 1,
            );

            if ( !$DeploymentResult{Success} ) {
                $LogObject->Log(
                    Priority => 'error',
                    Message  => "Deployment failed.",
                );

                return;
            }
        };

        # refresh the config object
        $Kernel::OM->ObjectsDiscard(
            Objects => ['Kernel::Config'],
        );
        $ConfigObject = $Kernel::OM->Get('Kernel::Config');
    }

    # Gnuplot::Bin might have been activated since the above check
    $GnuplotBin = $ConfigObject->Get($Key);
    if ( !$GnuplotBin ) {
        $LogObject->Log(
            Priority => 'info',
            Message  => 'Skipping switch to Gnuplot as Gnuplot::Bin is not in SysConfig.',
        );

        return 1;
    }

    if ( !-x $GnuplotBin ) {
        $LogObject->Log(
            Priority => 'info',
            Message  => qq{Skipping switch to Gnuplot as the gnuplot executable'$GnuplotBin' is not executable.},
        );

        return 1;
    }

    # deploy new sysconfig settings
    my $CommandObject = $Kernel::OM->Get('Kernel::System::Console::Command::Maint::Stats::Reports::SwitchFormat');
    my ( $Result, $ExitCode );
    {
        local *STDOUT;                      ## no critic qw(Variables::RequireInitializationForLocalVars)
        open STDOUT, '>:utf8', \$Result;    ## no critic qw(OTOBO::ProhibitOpen InputOutput::RequireEncodingWithUTF8Layer)
        $ExitCode = $CommandObject->Execute('--d3-to-gnuplot');
    }

    # exit code 0 means all went well
    if ($ExitCode) {
        $Kernel::OM->Get('Kernel::System::Log')->Log(
            Priority => 'error',
            Message  => "Could not switch the chart formats to 'Gnuplot::*'",
        );

        return;
    }

    # looking good
    return 1;
}

1;
